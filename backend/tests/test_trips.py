def test_trips_unauthorized_without_token():
    # GET /api/trips without token
    res_get = client.get("/api/trips")
    assert res_get.status_code == 401
    assert "Authentication required" in res_get.json()["detail"]

    # POST /api/trips without token
    res_post = client.post("/api/trips", json=SAMPLE_TRIP_PAYLOAD)
    assert res_post.status_code == 401

    # GET /api/trips/{id} without token
    res_detail = client.get(f"/api/trips/{uuid.uuid4()}")
    assert res_detail.status_code == 401

    # PATCH /api/trips/{id} without token
    res_patch = client.patch(f"/api/trips/{uuid.uuid4()}", json={"title": "New Title"})
    assert res_patch.status_code == 401

    # PUT /api/trips/{id} without token
    res_put = client.put(f"/api/trips/{uuid.uuid4()}", json=SAMPLE_TRIP_PAYLOAD)
    assert res_put.status_code == 401

    # DELETE /api/trips/{id} without token
    res_del = client.delete(f"/api/trips/{uuid.uuid4()}")
    assert res_del.status_code == 401


