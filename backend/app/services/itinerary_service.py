logger = logging.getLogger(__name__)

DEMO_NOTICE = (
    "Development demo \u2014 AI itinerary generation is not implemented yet. "
    "This response echoes your trip preferences and lists placeholder days with no activities."
)

GROQ_NOTICE = "Personalized itinerary generated by Trip Genius AI powered by Groq."


def generate_demo_itinerary(payload: ItineraryGenerateRequest) -> ItineraryGenerateResponse:
    day_count = (payload.end_date - payload.start_date).days + 1

    days = [
        ItineraryDay(
            day_number=index + 1,
            date=payload.start_date + timedelta(days=index),
            title=f"Day {index + 1} \u2014 awaiting generation",
            notes="Placeholder day. No itinerary activities have been generated.",
            activities=[],
        )
        for index in range(day_count)
    ]

    return ItineraryGenerateResponse(
        source="development_demo",
        notice=DEMO_NOTICE,
        destination=payload.destination,
        start_date=payload.start_date,
        end_date=payload.end_date,
        interests=payload.interests,
        budget=payload.budget,
        pace=payload.pace,
        day_count=day_count,
        days=days,
    )


def _format_activity(act: Any) -> str:
    if isinstance(act, str):
        return act.strip()
    if isinstance(act, dict):
        parts: list[str] = []
        for key in ("time", "time_of_day", "period"):
            if act.get(key):
                parts.append(f"{act[key]}:")
                break
        for key in ("title", "name", "activity", "description"):
            if act.get(key):
                parts.append(str(act[key]).strip())
                break
        for key in ("transport", "transportation"):
            if act.get(key):
                parts.append(f"Transport: {act[key]}")
        for key in ("food", "dining", "meal"):
            if act.get(key):
                parts.append(f"Food: {act[key]}")
        for key in ("cost", "estimated_cost", "price"):
            if act.get(key):
                parts.append(f"Cost: {act[key]}")
        if parts:
            return " ".join(parts).strip()
        return " - ".join(f"{k}: {v}" for k, v in act.items() if v).strip()
    return str(act).strip()


def build_groq_prompts(payload: ItineraryGenerateRequest, day_count: int) -> tuple[str, str]:
    system_prompt = (
        "You are an expert, meticulous travel planner for Trip Genius AI. "
        "Your task is to generate a comprehensive, highly personalized, realistic travel itinerary in JSON format.\n\n"
        "Output Requirements:\n"
        "1. Return ONLY a valid JSON object matching this schema:\n"
        "{\n"
        '  "days": [\n'
        "    {\n"
        '      "day_number": 1,\n'
        '      "title": "Concise evocative day theme",\n'
        '      "notes": "Day overview highlighting transport tips, neighborhood focus, and key food recommendations",\n'
        '      "activities": [\n'
        '        "Morning: [Activity description, venue name]. Transport: [Metro/bus/walk details]. Food: [Breakfast/brunch idea]. Cost: [Estimated cost per person]",\n'
        '        "Afternoon: [Activity description, venue name]. Transport: [Directions]. Food: [Lunch recommendation]. Cost: [Estimated cost per person]",\n'
        '        "Evening: [Activity description, venue name]. Transport: [Directions]. Food: [Dinner/drinks recommendation]. Cost: [Estimated cost per person]"\n'
        "      ]\n"
        "    }\n"
        "  ]\n"
        "}\n"
        f"2. You MUST generate exactly {day_count} days numbered sequentially from 1 to {day_count}.\n"
        "3. For each day, include distinct Morning, Afternoon, and Evening activities in the 'activities' array (at least 3 activities per day).\n"
        "4. Include realistic descriptions, transport advice (metro lines, walking, transit passes), specific food and restaurant/market recommendations, and estimated costs.\n"
        "5. Tailor the selections strictly to the user's destination, budget tier, travel pace, and interests.\n"
        "6. Do not include markdown formatting, backticks, or explanatory text outside the JSON object."
    )

    budget_guidance = {
        "budget": "Budget-friendly (free/low-cost sights, walking, public transit, street food and markets)",
        "moderate": "Moderate (balance of popular sights, museum admissions, casual dining, standard transit)",
        "premium": "Premium (top-tier tours, skip-the-line admissions, boutique dining, convenient taxis)",
        "luxury": "Luxury (exclusive experiences, fine dining/Michelin spots, private guides and chauffeured transit)",
    }.get(payload.budget, payload.budget)

    pace_guidance = {
        "relaxed": "Relaxed pace (2-3 unhurried activities per day with ample downtime)",
        "balanced": "Balanced pace (3-4 activities per day smoothly covering morning, afternoon, and evening)",
        "packed": "Packed pace (4-5 dynamic activities per day maximizing sightseeing from morning to night)",
    }.get(payload.pace, payload.pace)

    interests_str = ", ".join(payload.interests) if payload.interests else "General sightseeing"
    user_prompt = (
        f"Destination: {payload.destination}\n"
        f"Travel Dates: {payload.start_date} to {payload.end_date} ({day_count} day(s))\n"
        f"Interests: {interests_str}\n"
        f"Budget Tier: {payload.budget} ({budget_guidance})\n"
        f"Travel Pace: {payload.pace} ({pace_guidance})\n\n"
        f"Create a realistic, exciting {day_count}-day itinerary for {payload.destination} matching these traveler preferences."
    )

    return system_prompt, user_prompt


def get_groq_client() -> Groq:
    api_key = settings.groq_api_key.strip()
    if not api_key or api_key == "your-groq-api-key":
        raise HTTPException(
            status_code=status.HTTP_503_SERVICE_UNAVAILABLE,
            detail="Groq API key is not configured. Please set GROQ_API_KEY in backend/.env.",
        )
    return Groq(api_key=api_key, timeout=settings.groq_timeout_seconds)


def generate_groq_itinerary(payload: ItineraryGenerateRequest) -> ItineraryGenerateResponse:
    day_count = (payload.end_date - payload.start_date).days + 1
    system_prompt, user_prompt = build_groq_prompts(payload, day_count)

    client = get_groq_client()

    try:
        completion = client.chat.completions.create(
            model=settings.groq_model,
            messages=[
                {"role": "system", "content": system_prompt},
                {"role": "user", "content": user_prompt},
            ],
            response_format={"type": "json_object"},
            temperature=0.7,
        )
    except APITimeoutError as exc:
        logger.error(f"Groq API timeout: {exc}")
        raise HTTPException(
            status_code=status.HTTP_504_GATEWAY_TIMEOUT,
            detail="Groq itinerary generation timed out. Please try again.",
        ) from exc
    except RateLimitError as exc:
        logger.error(f"Groq rate limit exceeded: {exc}")
        raise HTTPException(
            status_code=status.HTTP_429_TOO_MANY_REQUESTS,
            detail="Groq rate limit exceeded. Please wait a moment and try again.",
        ) from exc
    except AuthenticationError as exc:
        logger.error(f"Groq authentication failed: {exc}")
        raise HTTPException(
            status_code=status.HTTP_502_BAD_GATEWAY,
            detail="Groq authentication failed. Please verify your GROQ_API_KEY.",
        ) from exc
    except APIConnectionError as exc:
        logger.error(f"Groq connection error: {exc}")
        raise HTTPException(
            status_code=status.HTTP_502_BAD_GATEWAY,
            detail="Could not connect to the Groq API service. Please check your network connection.",
        ) from exc
    except (APIStatusError, APIError) as exc:
        logger.error(f"Groq API error: {exc}")
        raise HTTPException(
            status_code=status.HTTP_502_BAD_GATEWAY,
            detail="An error occurred while communicating with Groq AI service.",
        ) from exc
    except HTTPException:
        raise
    except Exception as exc:
        logger.error(f"Unexpected error calling Groq: {exc}")
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail="Unexpected error occurred during itinerary generation.",
        ) from exc

    raw_content = completion.choices[0].message.content if completion.choices else None
    if not raw_content:
        raise HTTPException(
            status_code=status.HTTP_502_BAD_GATEWAY,
            detail="Received an empty response from the AI model.",
        )

    try:
        data = json.loads(raw_content)
    except Exception as exc:
        logger.error(f"Failed to parse JSON from Groq: {raw_content[:200]}")
        raise HTTPException(
            status_code=status.HTTP_502_BAD_GATEWAY,
            detail="Failed to parse a valid JSON itinerary from the AI model.",
        ) from exc

    raw_days = data.get("days")
    if not isinstance(raw_days, list) or len(raw_days) == 0:
        if isinstance(data, list):
            raw_days = data
        elif isinstance(data.get("itinerary"), list):
            raw_days = data.get("itinerary")
        elif isinstance(data.get("daily_plan"), list):
            raw_days = data.get("daily_plan")
        else:
            raise HTTPException(
                status_code=status.HTTP_502_BAD_GATEWAY,
                detail="Received an invalid itinerary structure: missing days list.",
            )

    if len(raw_days) < day_count:
        raise HTTPException(
            status_code=status.HTTP_502_BAD_GATEWAY,
            detail=f"Received incomplete itinerary: AI generated {len(raw_days)} days but trip requires {day_count} days.",
        )

    days: list[ItineraryDay] = []
    for index in range(day_count):
        day_number = index + 1
        day_date = payload.start_date + timedelta(days=index)

        # Match by day_number if present, otherwise fall back to array position
        raw_day = None
        for candidate in raw_days:
            if isinstance(candidate, dict) and candidate.get("day_number") == day_number:
                raw_day = candidate
                break
        if raw_day is None and index < len(raw_days) and isinstance(raw_days[index], dict):
            raw_day = raw_days[index]
        if raw_day is None:
            raw_day = {}

        title = str(raw_day.get("title") or f"Day {day_number} in {payload.destination}").strip()
        notes = str(raw_day.get("notes") or f"Explore {payload.destination} at your preferred pace.").strip()

        raw_activities = raw_day.get("activities")
        if isinstance(raw_activities, list):
            activities = [_format_activity(act) for act in raw_activities if _format_activity(act)]
        else:
            activities = []

        if not activities:
            raise HTTPException(
                status_code=status.HTTP_502_BAD_GATEWAY,
                detail=f"Received incomplete itinerary: Day {day_number} contains no activities.",
            )

        days.append(
            ItineraryDay(
                day_number=day_number,
                date=day_date,
                title=title,
                notes=notes,
                activities=activities,
            )
        )

    return ItineraryGenerateResponse(
        source="groq",
        notice=GROQ_NOTICE,
        destination=payload.destination,
        start_date=payload.start_date,
        end_date=payload.end_date,
        interests=payload.interests,
        budget=payload.budget,
        pace=payload.pace,
        day_count=day_count,
        days=days,
    )


def generate_itinerary_service(payload: ItineraryGenerateRequest) -> ItineraryGenerateResponse:
    if payload.demo:
        return generate_demo_itinerary(payload)
    return generate_groq_itinerary(payload)
